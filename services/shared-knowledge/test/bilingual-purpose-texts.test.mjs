import test from 'node:test';
import assert from 'node:assert/strict';
import {handle} from '../src/worker.ts';
import {AGREEMENT_VERSION} from '../src/rules.ts';
import {validEnglishPurposeTextPair} from '../src/purpose-text.ts';
import {database} from './sqlite-adapter.mjs';

const fp={softwareId:'generic-v3',versionMajor:'0',roleId:'path3:os-local/cache',shape:'purpose3-directory'};
const texts={shortPurpose:'应用临时缓存',reason:'应用生成的临时缓存',shortPurposeEn:'Application cache',reasonEn:'Temporary cache generated by the application.'};
async function fixture() {
  const env={DB:database(),SERVICE_MODE:'enabled'}; let network=0;
  const call=async(path,method='GET',body,who)=>{
    const response=await handle(new Request(`http://localhost${path}`,{method,
      headers:{'content-type':'application/json','CF-Connecting-IP':`10.24.0.${++network}`,
        ...(who?{'X-Installation-Id':who.installationId,Authorization:`Bearer ${who.managementToken}`}:{})},
      body:body===undefined?undefined:JSON.stringify(body)}),env);
    return {status:response.status,body:await response.json()};
  };
  const author=(await call('/v1/install','POST',{})).body;
  assert.equal((await call('/v1/consent','PUT',{expectedEpoch:0,enabled:true,agreementVersion:AGREEMENT_VERSION,
    shareHistory:false,policyRevision:'bilingual-texts'},author)).status,200);
  const contribution={...fp,analysisId:'bilingual-ai-0001',purpose:'cache',action:'Review',source:'fresh-ai',
    providerClass:'official',modelFamily:'deepseek',defaultPrompt:true,sharedContext:false,confidenceLevel:'High',...texts};
  const post=item=>call('/v1/contributions','POST',{epoch:1,items:[item??contribution]},author);
  const query=()=>call('/v1/query','POST',{epoch:1,items:[fp]},author);
  return {env,call,author,contribution,post,query};
}

test('bilingual text survives ingestion, storage, query and own listing without a second observation',async()=>{
  const f=await fixture();assert.equal((await f.post()).body.accepted,1);
  const row=f.env.DB.sqlite.prepare('SELECT * FROM contributions').get();
  assert.equal(row.short_purpose_en,texts.shortPurposeEn);assert.equal(row.reason_en,texts.reasonEn);
  const entry=(await f.query()).body.items[0].entry;
  for(const [key,value] of Object.entries(texts))assert.equal(entry[key],value);
  const mine=(await f.call('/v1/contributions','GET',undefined,f.author)).body.items[0];
  assert.equal(mine.shortPurposeEn,texts.shortPurposeEn);assert.equal(mine.reasonEn,texts.reasonEn);
  assert.equal((await f.post({...f.contribution,reasonEn:'A replay must not change the original.'})).body.accepted,0);
  assert.equal((await f.query()).body.items[0].entry.reasonEn,texts.reasonEn);
  assert.equal(f.env.DB.sqlite.prepare('SELECT COUNT(*) AS n FROM contributions').get().n,1);
  assert.equal(f.env.DB.sqlite.prepare('SELECT COUNT(*) AS n FROM analysis_receipts').get().n,1);
});

test('old clients remain readable and English text is never borrowed from a different original',async()=>{
  const f=await fixture();const legacy={...f.contribution};delete legacy.shortPurposeEn;delete legacy.reasonEn;
  assert.equal((await f.post(legacy)).body.accepted,1);
  const entry=(await f.query()).body.items[0].entry;
  assert.equal(entry.shortPurpose,texts.shortPurpose);assert.equal(entry.shortPurposeEn,'');assert.equal(entry.reasonEn,'');
});

test('English pair rejects partial, unsafe, non-English and oversized values before writing',async()=>{
  const f=await fixture();
  const bad=[{shortPurposeEn:''},{reasonEn:''},{shortPurposeEn:null},{reasonEn:null},
    {shortPurposeEn:'a'.repeat(81)},{reasonEn:'a'.repeat(241)},{reasonEn:'https://private.test'},
    {reasonEn:'Contact user@example.com'},{reasonEn:'User password backup'},{reasonEn:'Private username'},
    {reasonEn:'C:\\Users\\Alice'},{reasonEn:'中文说明'},{shortPurposeEn:' Cache'},
    {shortPurpose:'',reason:''}];
  for(const fields of bad)assert.equal((await f.post({...f.contribution,...fields})).status,400,JSON.stringify(fields));
  assert.equal(f.env.DB.sqlite.prepare('SELECT COUNT(*) AS n FROM contributions').get().n,0);
  assert.equal(validEnglishPurposeTextPair('a'.repeat(80),'b'.repeat(240)),true);
  assert.equal(validEnglishPurposeTextPair('',''),true);
});

test('translation backfill preserves evidence identity, dates, receipts and consensus',async()=>{
  const f=await fixture();const legacy={...f.contribution};delete legacy.shortPurposeEn;delete legacy.reasonEn;
  await f.post(legacy);
  const before=f.env.DB.sqlite.prepare('SELECT * FROM contributions').get();
  f.env.DB.sqlite.prepare('UPDATE contributions SET short_purpose_en=?,reason_en=? WHERE id=?')
    .run(texts.shortPurposeEn,texts.reasonEn,before.id);
  const after=f.env.DB.sqlite.prepare('SELECT * FROM contributions').get();
  for(const key of Object.keys(before).filter(key=>!['short_purpose_en','reason_en'].includes(key)))assert.equal(after[key],before[key],key);
  assert.equal((await f.query()).body.items[0].entry.reasonEn,texts.reasonEn);
  assert.equal(f.env.DB.sqlite.prepare('SELECT COUNT(*) AS n FROM analysis_receipts').get().n,1);
});
