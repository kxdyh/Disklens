import assert from 'node:assert/strict';
import {AGREEMENT_VERSION, RULE_VERSION} from '../src/rules.ts';

// Opt-in smoke test against an isolated Wrangler LOCAL database only.
// Never follow a redirect or send synthetic evidence to a public origin.
const origin=process.env.SHARED_LOCAL_ORIGIN ?? 'http://127.0.0.1:8791';
assert.match(origin,/^http:\/\/(127\.0\.0\.1|localhost):\d+$/);
const installations=[],stages=[],requests=[];
async function call(path,method='GET',data,who) {
  const response=await fetch(origin+path,{method,redirect:'error',signal:AbortSignal.timeout(15000),
    headers:{...(data!==undefined?{'Content-Type':'application/json'}:{}),
      ...(who?{'X-Installation-Id':who.installationId,Authorization:`Bearer ${who.managementToken}`}:{})},
    body:data!==undefined?JSON.stringify(data):undefined});
  const body=await response.json();
  // Status-only evidence deliberately excludes installation credentials.
  requests.push({method,path,status:response.status,...(body.error?{error:body.error}:{})});
  return {status:response.status,body};
}
async function register() {
  const registration=await call('/v1/install','POST',{});
  assert.equal(registration.status,201);
  const who=registration.body;installations.push(who);
  const state=await call('/v1/consent','GET',undefined,who);
  assert.equal(state.status,200);assert.equal(state.body.enabled,false);assert.equal(state.body.epoch,0);
  return who;
}
async function consent(who,expectedEpoch,enabled) {
  return call('/v1/consent','PUT',{expectedEpoch,enabled,agreementVersion:AGREEMENT_VERSION,
    shareHistory:false,policyRevision:'local-http-path3'},who);
}
const fixtureKey=crypto.randomUUID().replaceAll('-','').padEnd(64,'0');
const fingerprint=roleId=>({softwareId:'generic-v3',versionMajor:'0',roleId:`path3:${roleId}`,shape:`purpose3-shared-directory-${fixtureKey}`});
const contribution=(fp,confidenceLevel,purpose='cache',action='Review')=>({...fp,analysisId:crypto.randomUUID(),
  purpose,action,source:'fresh-ai',providerClass:'official',modelFamily:'deepseek',defaultPrompt:true,
  sharedContext:false,confidenceLevel,shortPurpose:'应用临时缓存',reason:'应用生成的临时缓存，仍需核验本机使用状态',
  shortPurposeEn:'Application cache',reasonEn:'Temporary cache generated by the application. Check its current local use.'});
const mediumFp=fingerprint('os-local/cache'),highFp=fingerprint('os-temp/logs');
const medium=contribution(mediumFp,'Medium');
const high={...contribution(highFp,'High','logs'),shortPurpose:'程序运行日志',reason:'程序运行期间记录的日志，仍需核验本机使用状态',
  shortPurposeEn:'Application runtime logs',reasonEn:'Logs recorded while the application runs. Check its current local use.'};
const low=contribution(fingerprint('os-local/configuration'),'Low','configuration','Keep');
const unknown=contribution(fingerprint('os-roaming/cache'),'Unknown');
const {confidenceLevel:_unused,...missing}=contribution(fingerprint('os-temp/cache'),'Unknown');
const payload=[medium,high,low,unknown,missing];
let failure,cleaned=0;
try {
  const rules=await call('/v1/rules');
  assert.equal(rules.status,200);assert.equal(rules.body.ruleVersion,RULE_VERSION);
  assert.equal(rules.body.agreementVersion,AGREEMENT_VERSION);assert.equal(rules.body.purposeProtocol,'path3');
  stages.push('rules-path3');
  const author=await register(),reader=await register();
  assert.notEqual(author.installationId,reader.installationId);
  stages.push('independent-installations-default-disabled');
  assert.equal((await call('/v1/query','POST',{epoch:0,items:[mediumFp]},reader)).status,403);
  assert.equal((await call('/v1/contributions','POST',{epoch:0,items:[medium]},author)).status,403);
  stages.push('reject-query-and-upload-before-consent');
  for(const who of [author,reader]) {
    const enabled=await consent(who,0,true);
    assert.equal(enabled.status,200);assert.equal(enabled.body.epoch,1);assert.equal(enabled.body.enabled,true);
  }
  stages.push('explicit-current-agreement-consent');
  let query=await call('/v1/query','POST',{epoch:1,items:[mediumFp,highFp]},reader);
  assert.equal(query.status,200);assert.ok(query.body.items.every(item=>item.matched===false));
  stages.push('safe-miss-before-contribution');
  const posted=await call('/v1/contributions','POST',{epoch:1,items:payload},author);
  assert.equal(posted.status,200);assert.deepEqual(posted.body,{epoch:1,accepted:2,skipped:3,migrated:0,blockedUpgrades:[]});
  stages.push('medium-high-accepted-low-unknown-missing-filtered');
  query=await call('/v1/query','POST',{epoch:1,items:[mediumFp,highFp]},reader);
  assert.equal(query.status,200);assert.equal(query.body.items.length,2);
  for(const [index,expected] of [medium,high].entries()) {
    const item=query.body.items[index];assert.equal(item.matched,true);
    for(const field of ['roleId','purpose','action','confidenceLevel','shortPurpose','reason','shortPurposeEn','reasonEn'])
      assert.equal(item.entry[field],expected[field]);
    assert.ok(item.entry.conditions.some(condition=>condition.includes('不构成删除许可')));
  }
  stages.push('independent-reader-reuses-medium-high-original-text-without-deletion-authority');
  const filtered=await call('/v1/query','POST',{epoch:1,items:[low,unknown,missing].map(({softwareId,versionMajor,roleId,shape})=>({softwareId,versionMajor,roleId,shape}))},reader);
  assert.equal(filtered.status,200);assert.ok(filtered.body.items.every(item=>item.matched===false));
  stages.push('low-unknown-missing-not-reusable');
  const replay=await call('/v1/contributions','POST',{epoch:1,items:payload.toReversed()},author);
  assert.equal(replay.status,200);assert.deepEqual(replay.body,{epoch:1,accepted:0,skipped:5,migrated:0,blockedUpgrades:[]});
  stages.push('idempotent-replay');
  const mine=await call('/v1/contributions','GET',undefined,author);
  assert.equal(mine.status,200);assert.equal(mine.body.items.length,2);
  assert.deepEqual(mine.body.items.map(item=>item.confidenceLevel).sort(),['High','Medium']);
  assert.ok(!JSON.stringify(mine.body).includes(author.managementToken));
  assert.equal((await call('/v1/contributions','GET',undefined,reader)).body.items.length,0);
  stages.push('own-list-retains-only-eligible-contributions');
  const removed=await call('/v1/contributions?epoch=1','DELETE',undefined,author);
  assert.equal(removed.status,200);assert.deepEqual(removed.body,{epoch:2,withdrawn:2,cleanupDeleted:2,cleanupPending:false,allWithdrawn:true});
  stages.push('withdraw-all-advances-epoch');
  query=await call('/v1/query','POST',{epoch:1,items:[mediumFp,highFp]},reader);
  assert.equal(query.status,200);assert.ok(query.body.items.every(item=>item.matched===false));
  assert.equal((await call('/v1/contributions','GET',undefined,author)).body.items.length,0);
  stages.push('withdrawal-immediately-removes-independent-reuse');
  for(const [path,method,data] of [
    ['/v1/contributions','POST',{epoch:1,items:[{...medium,analysisId:crypto.randomUUID()}]}],
    ['/v1/query','POST',{epoch:1,items:[mediumFp]}],
    ['/v1/contributions?epoch=1','DELETE',undefined],
  ]) {
    const stale=await call(path,method,data,author);
    assert.equal(stale.status,409);assert.equal(stale.body.error,'stale_epoch');assert.equal(stale.body.epoch,2);
  }
  stages.push('stale-epoch-upload-query-withdraw-rejected');
  const afterWithdrawal=await call('/v1/contributions','POST',{epoch:2,items:payload},author);
  assert.equal(afterWithdrawal.status,200);assert.deepEqual(afterWithdrawal.body,{epoch:2,accepted:0,skipped:5,migrated:0,blockedUpgrades:[]});
  assert.equal((await call('/v1/contributions','GET',undefined,author)).body.items.length,0);
  stages.push('original-analysis-receipts-prevent-revival-after-withdrawal');
  for(const [who,epoch] of [[author,2],[reader,1]]) {
    const disabled=await consent(who,epoch,false);
    assert.equal(disabled.status,200);assert.equal(disabled.body.epoch,epoch+1);assert.equal(disabled.body.enabled,false);
    assert.equal((await call('/v1/query','POST',{epoch:epoch+1,items:[mediumFp]},who)).status,403);
  }
  stages.push('disable-both-installations-and-reject-query');
} catch(error) {failure=error;}
finally {
  // Complete withdrawal/disable cleanup even if an earlier assertion failed.
  for(const who of installations) try {
    let state=(await call('/v1/consent','GET',undefined,who)).body;
    const entries=(await call('/v1/contributions','GET',undefined,who)).body.items;
    if(entries?.length) {
      const removed=await call(`/v1/contributions?epoch=${state.epoch}`,'DELETE',undefined,who);
      assert.equal(removed.status,200);state={...state,...removed.body};
    }
    if(state.enabled) assert.equal((await consent(who,state.epoch,false)).status,200);
    const final=(await call('/v1/consent','GET',undefined,who)).body;
    assert.equal(final.enabled,false);
    assert.equal((await call('/v1/contributions','GET',undefined,who)).body.items.length,0);
    cleaned++;
  } catch(error) {failure??=error;}
}
console.log(JSON.stringify({localOnly:true,origin,purposeProtocol:'path3',success:!failure,
  passed:stages.length,stages,cleanup:{installations:installations.length,disabledAndEmpty:cleaned},requests},null,2));
if(failure) throw failure;
