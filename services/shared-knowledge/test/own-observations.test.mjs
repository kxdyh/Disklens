import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {handle} from '../src/worker.ts';
import {AGREEMENT_VERSION} from '../src/rules.ts';
import {database} from './sqlite-adapter.mjs';

const fp={softwareId:'generic-v3',versionMajor:'0',roleId:'path3:os-local/mask',shape:'purpose3-observation-directory-'+'a'.repeat(32)};
const texts={shortPurpose:'应用临时缓存',reason:'应用生成的临时缓存',shortPurposeEn:'Application cache',reasonEn:'Temporary cache generated by the application.'};
const key=f=>[f.softwareId,f.versionMajor,f.roleId,f.shape].join('|');
function fixture() {
  const env={DB:database(),SERVICE_MODE:'enabled'};
  function install() {
    const id=crypto.randomUUID(), token='S'.repeat(43), now=Date.now();
    env.DB.sqlite.prepare('INSERT INTO installations(id,token_hash,created_at,epoch,enabled,agreement_version,policy_revision) VALUES(?,?,?,1,1,?,?)')
      .run(id,createHash('sha256').update(token).digest('hex'),now-3600000,AGREEMENT_VERSION,'own-observations');
    return {id,token};
  }
  function seed(who,f=fp,overrides={}) {
    const now=Date.now(),id=crypto.randomUUID().replaceAll('-','').repeat(2), full={...texts,purpose:'cache',action:'Review',grade:'High',updatedAt:now,withdrawn:0,...overrides};
    env.DB.sqlite.prepare('INSERT INTO buckets(key,software_id,version_major,role_id,shape,updated_at) VALUES(?,?,?,?,?,?) ON CONFLICT DO NOTHING')
      .run(key(f),f.softwareId,f.versionMajor,f.roleId,f.shape,now);
    env.DB.sqlite.prepare(`INSERT INTO contributions(id,installation_id,analysis_id,bucket_key,purpose,action,source,provider_class,model_family,default_prompt,shared_context,epoch,first_observed,updated_at,withdrawn,confidence_level,short_purpose,reason,short_purpose_en,reason_en)
      VALUES(?,?,?,?,?,?,'fresh-ai',?,?,?, ?,1,?,?,?,?,?,?,?,?)`)
      .run(id,who.id,'own_analysis_'+crypto.randomUUID(),key(f),full.purpose,full.action,full.providerClass??'official','deepseek',full.defaultPrompt??1,full.sharedContext??0,now,full.updatedAt,full.withdrawn,full.grade,full.shortPurpose,full.reason,full.shortPurposeEn,full.reasonEn);
    return id;
  }
  async function call(who,items=[fp],epoch=1,path='/v1/observations/query') {
    const response=await handle(new Request('http://localhost'+path,{method:'POST',headers:{'Content-Type':'application/json',
      'CF-Connecting-IP':'10.18.0.1','X-Installation-Id':who.id,Authorization:'Bearer '+who.token},body:JSON.stringify({epoch,items})}),env);
    return {status:response.status,body:await response.json()};
  }
  return {env,install,seed,call};
}

test('an exact observation restores only its current installation original bilingual result',async()=>{
  const f=fixture(),author=f.install(),other=f.install();f.seed(author);
  const own=await f.call(author);assert.equal(own.status,200);const item=own.body.items[0];
  assert.equal(item.matched,true);assert.equal(item.key,key(fp));assert.equal(item.entry.isOwnObservation,true);
  for(const [name,value] of Object.entries(texts))assert.equal(item.entry[name],value);
  assert.equal(item.entry.confidenceLevel,'High');assert.equal(item.entry.action,'Review');assert.ok(Date.parse(item.entry.expiresAt)>Date.now());
  assert.equal((await f.call(other)).body.items[0].matched,false);
  const serialized=JSON.stringify(own.body);for(const value of [author.id,author.token,'analysisId','installationId'])assert.equal(serialized.includes(value),false);
});

test('opaque file observation is recoverable only by exact key and global consensus still always misses',async()=>{
  const f=fixture(),who=f.install();const file={...fp,roleId:'path3:os-downloads/file-zip',shape:'purpose3-observation-file-'+'b'.repeat(32)};
  f.seed(who,file);
  assert.equal((await f.call(who,[file])).body.items[0].matched,true);
  assert.equal((await f.call(who,[{...file,shape:'purpose3-observation-file-'+'c'.repeat(32)}])).body.items[0].matched,false);
  assert.equal((await f.call(who,[file],1,'/v1/query')).body.items[0].matched,false);
});

test('own-observation route rejects reusable legacy malformed and oversized fingerprint batches',async()=>{
  const f=fixture(),who=f.install();f.seed(who);
  for(const value of [{...fp,shape:'purpose3-directory'},{...fp,roleId:'path3:os-local/private-name'},{...fp,shape:fp.shape.toUpperCase()}])
    assert.equal((await f.call(who,[value])).status,400);
  assert.equal((await f.call(who,Array(26).fill(fp))).status,400);assert.equal((await f.call(who,[])).status,400);
});

test('unknown, category-only, low, withdrawn, or unsafe own records cannot be restored',async()=>{
  const cases=[{purpose:'unknown'},{shortPurpose:'',reason:'',shortPurposeEn:'',reasonEn:''},{grade:'Low'},
    {grade:'Unknown'},{withdrawn:1},
    {reason:'C:\\Users\\Private'},{shortPurposeEn:'English title',reasonEn:''}];
  for(const overrides of cases) {
    const f=fixture(),who=f.install();f.seed(who,fp,overrides);
    const result=await f.call(who);assert.equal(result.status,200,JSON.stringify(overrides));assert.equal(result.body.items[0].matched,false,JSON.stringify(overrides));
  }
});

test('legacy absent English is allowed only with the complete original Chinese pair',async()=>{
  const f=fixture(),who=f.install();f.seed(who,fp,{shortPurposeEn:'',reasonEn:'',grade:'Medium'});
  const result=await f.call(who);assert.equal(result.status,200);assert.equal(result.body.items[0].matched,true);
  assert.equal(result.body.items[0].entry.shortPurposeEn,'');assert.equal(result.body.items[0].entry.confidenceLevel,'Medium');
});

test('stale or revoked current consent blocks own observations and read-only mode permits the query',async()=>{
  const f=fixture(),who=f.install();f.seed(who);
  assert.equal((await f.call(who,[fp],0)).status,409);
  f.env.SERVICE_MODE='read-only';assert.equal((await f.call(who)).body.items[0].matched,true);
  f.env.DB.sqlite.prepare('UPDATE installations SET enabled=0 WHERE id=?').run(who.id);
  assert.equal((await f.call(who)).status,403);
});

test('consent changed while the own-observation D1 snapshot is in flight cannot return a hit',async()=>{
  const f=fixture(),who=f.install();f.seed(who);
  const originalBatch=f.env.DB.batch.bind(f.env.DB);
  f.env.DB.batch=async statements=>{
    const results=await originalBatch(statements);
    f.env.DB.sqlite.prepare('UPDATE installations SET epoch=epoch+1,enabled=0 WHERE id=?').run(who.id);
    return results;
  };
  const result=await f.call(who);assert.equal(result.status,409);assert.equal('items' in result.body,false);
});
