    [Fact]
    public async Task Legacy_rows_do_not_invent_a_short_purpose_and_keep_safe_category_fallback_only_on_right()
    {
        var client = new Client { Response = Entry() with { ShortPurpose = "", Reason = "", ShortPurposeEn = "", ReasonEn = "" } };
        var resolved = Assert.Single((await new SharedKnowledgePipeline(new Consent(), new Extractor(), client)
            .ResolveAsync([Candidate()])).ResultsByPath).Value;
        Assert.Empty(resolved.ShortPurpose);
        Assert.Empty(resolved.ShortPurposeEn);
        Assert.Empty(resolved.ReasonEn);
        Assert.Equal("应用缓存与临时数据", resolved.Reason);
        var consent = new Consent(); var candidate = Candidate();
        await new SharedKnowledgePipeline(consent, new Extractor(), client).ContributeAsync([candidate],
            [Result(candidate.Path) with { ShortPurpose = "", Reason = "legacy reason may contain C:\\Users\\PrivateAccount", ShortPurposeEn = "", ReasonEn = "" }], Provenance(consent));
        var contribution = Assert.Single(client.Contributions);
        Assert.Empty(contribution.ShortPurpose); Assert.Empty(contribution.Reason);
    }

    [Theory]
    [InlineData("缓存", "位于C:\\Users\\Alice的缓存")]
    [InlineData("缓存", "联系user@example.com")]
    [InlineData("缓存", "sk-secret-key")]
    [InlineData("缓存", "API Key数据")]
    [InlineData("缓存", "用户密码数据")]
    [InlineData("缓存", "13812345678")]
    [InlineData("缓存", "<script>内容</script>")]
    [InlineData("缓存", "缓存\n用途")]
    [InlineData("缓存", "")]
    [InlineData("", "应用缓存")]
    [InlineData("这是超过十二字长度限制的缓存用途", "应用缓存")]
    public async Task Unsafe_or_partial_dual_text_is_skipped_without_rewriting(string shortPurpose, string reason)
    {
        var consent = new Consent(); var candidate = Candidate(); var client = new Client();
        var receipt = await new SharedKnowledgePipeline(consent, new Extractor(), client).ContributeAsync([candidate],
            [Result(candidate.Path) with { ShortPurpose = shortPurpose, Reason = reason,
                ShortPurposeEn = shortPurpose.Length == 0 ? "" : ShortEn,
                ReasonEn = shortPurpose.Length == 0 ? "" : DetailEn }], Provenance(consent));
        // Empty short purpose denotes a legacy record; its free reason must not be sent.
        if (shortPurpose.Length == 0)
        {
            Assert.Empty(Assert.Single(client.Contributions).Reason);
            return;
        }
        Assert.Equal(0, receipt.Accepted); Assert.Empty(client.Contributions);
    }

