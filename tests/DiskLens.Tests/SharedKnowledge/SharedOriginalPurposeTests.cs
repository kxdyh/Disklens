    private const string Short = "应用临时缓存";
    private const string Detail = "应用生成的临时缓存，可在关闭相关程序后清理";
    private const string ShortEn = "Temporary application cache";
    private const string DetailEn = "Temporary cache generated by applications";
    private static readonly SharedFingerprint Fingerprint = new("generic-v3", "0", "path3:os-local/cache", "purpose3-directory");

    [Fact]
    public async Task Original_dual_texts_round_trip_through_contribution_wire_query_and_resolved_result()
    {
        string? payload = null;
        var consent = new Consent();
        using var client = new SharedExperienceClient(new Uri("http://localhost:8791/"), new Handler(async request =>
        {
            if (request.RequestUri!.AbsolutePath.EndsWith("contributions"))
            {
                payload = await request.Content!.ReadAsStringAsync();
                return Reply("{\"accepted\":1,\"skipped\":0,\"epoch\":1}");
            }
            return Reply(JsonSerializer.Serialize(new SharedQueryResponse([new(Fingerprint.Key, true, Entry())]),
                new JsonSerializerOptions(JsonSerializerDefaults.Web)));
        }));
        var candidate = Candidate();
        var pipeline = new SharedKnowledgePipeline(consent, new Extractor(), client);
        var receipt = await pipeline.ContributeAsync([candidate], [Result(candidate.Path)], Provenance(consent));
        Assert.Equal(1, receipt.Accepted);
        using var document = JsonDocument.Parse(payload!);
        var item = document.RootElement.GetProperty("items")[0];
        Assert.Equal(Short, item.GetProperty("shortPurpose").GetString());
        Assert.Equal(Detail, item.GetProperty("reason").GetString());
        Assert.Equal(ShortEn, item.GetProperty("shortPurposeEn").GetString());
        Assert.Equal(DetailEn, item.GetProperty("reasonEn").GetString());
        Assert.DoesNotContain(candidate.Path, payload!);
        var shared = Assert.Single((await pipeline.ResolveAsync([candidate])).ResultsByPath).Value;
        Assert.Equal(Short, shared.ShortPurpose);
        Assert.Equal(Detail, shared.Reason);
        Assert.Equal(ShortEn, shared.ShortPurposeEn);
        Assert.Equal(DetailEn, shared.ReasonEn);
        Assert.Equal(AiAnalysisResultOrigin.SharedExperience, shared.Origin);
        Assert.Null(shared.OriginalAnalysisId);
        // A cloud answer is not a new independent original AI contribution.
        Assert.Equal(0, (await pipeline.ContributeAsync([candidate], [shared], Provenance(consent))).Accepted);
    }

