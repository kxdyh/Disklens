    [Fact]
    public async Task Same_bucket_skips_the_low_record_and_keeps_the_eligible_original_pair_regardless_of_order()
    {
        var consent = new Consent(); var client = new Client(); var first = Candidate();
        var second = Candidate(@"C:\Users\PrivateAccount\AppData\Local\Temp");
        var high = Result(first.Path);
        var low = Result(second.Path) with
        {
            OriginalAnalysisId = "lower-confidence-original", ConfidenceLevel = AiConfidenceLevel.Low,
            ShortPurpose = "可能的缓存", Reason = "用途不确定的低置信度结果",
        };
        var pipeline = new SharedKnowledgePipeline(consent, new Extractor(), client);
        await pipeline.ContributeAsync([second, first], [low, high], Provenance(consent));
        await pipeline.ContributeAsync([first, second], [high, low], Provenance(consent));
        Assert.Equal(2, client.Contributions.Count);
        Assert.All(client.Contributions, contribution =>
        {
            Assert.Equal(high.OriginalAnalysisId, contribution.AnalysisId);
            Assert.Equal("High", contribution.ConfidenceLevel);
            Assert.Equal(high.ShortPurpose, contribution.ShortPurpose);
            Assert.Equal(high.Reason, contribution.Reason);
        });
    }

    [Fact]
    public async Task Malformed_remote_texts_are_not_displayed_and_client_rejects_unsafe_outgoing_payloads()
    {
        var client = new Client { Response = Entry() with { Reason = "https://private.example" } };
        Assert.Empty((await new SharedKnowledgePipeline(new Consent(), new Extractor(), client)
            .ResolveAsync([Candidate()])).ResultsByPath);
        using var wire = new SharedExperienceClient(new Uri("http://localhost:8791/"),
            new Handler(_ => throw new InvalidOperationException("Unsafe payload must not reach transport")));
        var contribution = new SharedContribution("original-id-1234", Fingerprint.SoftwareId, Fingerprint.VersionMajor,
            Fingerprint.RoleId, Fingerprint.Shape, "cache", "Review", "fresh-ai", "official", "deepseek", true, false, "High")
            { ShortPurpose = "缓存", Reason = "C:\\Users\\Alice" };
        await Assert.ThrowsAsync<ArgumentException>(() => wire.ContributeAsync(new("install", "secret", 1), 1, [contribution]));
        Assert.Equal(AiPurposeTextContract.MaximumShortPurposeLength, SharedPurposeText.MaximumShortPurposeLength);
        Assert.Equal(AiPurposeTextContract.MaximumReasonLength, SharedPurposeText.MaximumReasonLength);
    }

    private static AiCandidateRecord Candidate(string path = @"C:\Users\PrivateAccount\AppData\Local\Cache") =>
        SharedFingerprintTests.Record(path, SharedFingerprintTests.Node(path, size: 1024))
            with { AnalysisEvidenceScope = AiAnalysisEvidenceScope.PathPurpose };
    private static AiAnalysisResult Result(string path) => new(path, RiskLevel.Review, SuggestedAction.RecycleCandidate, Detail, .9)
    {
        ShortPurpose = Short, ConfidenceLevel = AiConfidenceLevel.High, PurposeCategory = "cache",
        ShortPurposeEn = ShortEn, ReasonEn = DetailEn,
        OriginalAnalysisId = "original-purpose-1234", OriginalAnalyzedAt = DateTimeOffset.UtcNow,
        AnalysisEvidenceScope = AiAnalysisEvidenceScope.PathPurpose,
    };
    private static SharedExperienceEntry Entry() => new(Fingerprint.Key, Fingerprint.SoftwareId, "untrusted label", Fingerprint.RoleId,
        "untrusted label", "cache", "Review", [], "untrusted explanation", 2, 1, "active", DateTimeOffset.UtcNow.AddMinutes(15), DateTimeOffset.UtcNow.AddMinutes(-1))
        { ConfidenceLevel = "High", ShortPurpose = Short, Reason = Detail, ShortPurposeEn = ShortEn, ReasonEn = DetailEn };
    private static SharedAnalysisProvenance Provenance(Consent consent) => new("official", "deepseek", true) { ConsentAtAnalysisStart = consent.Value };
    private sealed class Consent : ISharedConsentSource
    {
        public SharedConsentSnapshot Value { get; set; } = new(true, SharedConsentSnapshot.CurrentAgreementVersion,
            false, DateTimeOffset.UtcNow.AddMinutes(-5), 1, "dual-purpose-policy", [], new("install", "secret", 1));
        public Task<SharedConsentSnapshot> GetSnapshotAsync(CancellationToken cancellationToken = default) => Task.FromResult(Value);
    }
    private sealed class Extractor : ISharedFingerprintExtractor
    {
        public Task<SharedFingerprint?> ExtractAsync(AiCandidateRecord candidate, IReadOnlyList<string> exclusions,
            CancellationToken cancellationToken = default) => Task.FromResult<SharedFingerprint?>(Fingerprint);
    }
    private sealed class Outbox : ISharedContributionOutbox
    {
        public IReadOnlyList<SharedQueuedContribution> Items { get; private set; } = [];
        public Task EnqueueAsync(SharedConsentSnapshot consent, IReadOnlyList<SharedQueuedContribution> items, CancellationToken cancellationToken = default)
        { Items = items; return Task.CompletedTask; }
        public Task<SharedContributionReceipt> FlushAsync(CancellationToken cancellationToken = default) => Task.FromResult(new SharedContributionReceipt(Items.Count, 0, 1));
        public Task<int> PendingCountAsync(CancellationToken cancellationToken = default) => Task.FromResult(Items.Count);
        public Task SynchronizeConsentAsync(CancellationToken cancellationToken = default) => Task.CompletedTask;
    }
    private sealed class Handler(Func<HttpRequestMessage, Task<HttpResponseMessage>> send) : HttpMessageHandler
    {
        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken) => send(request);
    }
    private static HttpResponseMessage Reply(string json) => new(HttpStatusCode.OK) { Content = new StringContent(json, Encoding.UTF8, "application/json") };
    private sealed class Client : ISharedExperienceClient
    {
        public SharedExperienceEntry Response { get; set; } = Entry();
        public List<SharedContribution> Contributions { get; } = [];
        public int Uploads;
        public Task<SharedQueryResponse> QueryAsync(SharedInstallation installation, long epoch, IReadOnlyList<SharedFingerprint> items, CancellationToken cancellationToken = default)
            => Task.FromResult(new SharedQueryResponse([new(Fingerprint.Key, true, Response)]));
        public Task<SharedContributionReceipt> ContributeAsync(SharedInstallation installation, long epoch, IReadOnlyList<SharedContribution> items, CancellationToken cancellationToken = default)
        { Uploads++; Contributions.AddRange(items); return Task.FromResult(new SharedContributionReceipt(items.Count, 0, epoch)); }
        public Task<SharedInstallation> RegisterAsync(CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public Task<SharedConsentState> GetConsentAsync(SharedInstallation installation, CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public Task<SharedConsentState> UpdateConsentAsync(SharedInstallation installation, SharedConsentUpdate update, CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public Task<SharedContributionList> ListContributionsAsync(SharedInstallation installation, CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public Task<SharedWithdrawalReceipt> WithdrawAsync(SharedInstallation installation, long epoch, string? contributionId = null, CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public Task FeedbackAsync(SharedInstallation installation, long epoch, string key, string reason, CancellationToken cancellationToken = default) => throw new NotSupportedException();
    }
